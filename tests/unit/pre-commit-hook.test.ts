/**
 * The secret-detection pre-commit hook works as a HOOK (Phase 0.H, brief
 * item 5): a `git commit` that stages a secret is refused, a clean one goes
 * through. `detect-secrets.test.ts` drives the scanner directly; this drives
 * git, through the repository's own `.husky/pre-commit`, in a throwaway
 * repository (nothing is written to this one). CI's half — the same scanner
 * over every tracked file — is pinned by ci-workflow.test.ts, and
 * tests/guards/no-secrets.test.ts runs the patterns on every `npm test`.
 *
 * Husky v9 installs by pointing `core.hooksPath` at `.husky/_`, whose stub
 * runs `.husky/pre-commit` with `sh -e`; the stub is generated by `npm install`
 * (the `prepare` script), so here `core.hooksPath` points at a directory whose
 * `pre-commit` does exactly that.
 */
import { execFileSync, spawnSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';

const ROOT = path.resolve(__dirname, '../..');
let repo: string;

function git(...args: string[]) {
    return spawnSync('git', args, { cwd: repo, encoding: 'utf8', env: { ...process.env, NO_COLOR: '1' } });
}

beforeEach(() => {
    repo = fs.mkdtempSync(path.join(os.tmpdir(), 'ink-hook-'));
    execFileSync('git', ['init', '-q', '-b', 'main'], { cwd: repo });
    git('config', 'user.email', 'hook-test@example.test');
    git('config', 'user.name', 'Hook Test');
    git('config', 'commit.gpgsign', 'false');
    for (const f of ['.husky/pre-commit', 'scripts/detect-secrets.sh', '.secret-patterns']) {
        fs.mkdirSync(path.join(repo, path.dirname(f)), { recursive: true });
        fs.copyFileSync(path.join(ROOT, f), path.join(repo, f));
    }
    const stubDir = path.join(repo, '.husky', '_');
    fs.mkdirSync(stubDir, { recursive: true });
    fs.writeFileSync(path.join(stubDir, 'pre-commit'), '#!/bin/sh\nexec sh -e .husky/pre-commit "$@"\n', { mode: 0o755 });
    git('config', 'core.hooksPath', '.husky/_');
});

afterEach(() => fs.rmSync(repo, { recursive: true, force: true }));

it('package.json installs the hook (husky runs on prepare)', () => {
    const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
    expect(pkg.scripts.prepare).toBe('husky');
    expect(fs.readFileSync(path.join(ROOT, '.husky/pre-commit'), 'utf8')).toMatch(/^bash scripts\/detect-secrets\.sh$/m);
});

it('refuses a commit that stages a secret, naming the file', () => {
    // Assembled at run time: a literal would trip this repository's own scan.
    const key = ['AKIA', 'IOSFODNN7', 'EXAMPLE'].join('');
    fs.writeFileSync(path.join(repo, 'config.ts'), `export const accessKey = "${key}";\n`);
    git('add', 'config.ts');
    const r = git('commit', '-q', '-m', 'add config');
    expect(r.status).not.toBe(0);
    expect(`${r.stdout}${r.stderr}`).toMatch(/config\.ts/);
    expect(git('rev-parse', '--verify', 'HEAD').status).not.toBe(0);
});

it('refuses a staged .env file by name', () => {
    fs.writeFileSync(path.join(repo, '.env'), 'NOTHING=here\n');
    git('add', '-f', '.env');
    expect(git('commit', '-q', '-m', 'env').status).not.toBe(0);
});

it('lets a clean commit through', () => {
    fs.writeFileSync(path.join(repo, 'clean.ts'), 'export const answer = 42;\n');
    git('add', 'clean.ts');
    const r = git('commit', '-q', '-m', 'clean');
    expect([r.status, r.stderr]).toEqual([0, '']);
});
